#!/bin/bash
# Build a BINARY-ONLY, time-limited evaluation package of the Mac plugin.
#
#   ./package_eval_mac.sh [days]     (default 14)
#
# Output: tmp/GldfImporter-Mac-eval-until-<date>.zip containing only
# GldfImporter.uplugin + Binaries/Mac + Content — no Source, no ThirdParty
# (the Rust staticlibs are already linked into the dylibs).
#
# How the expiry works: a generated Private/GldfEvalExpiry.h defines
# GLDF_EVAL_EXPIRY_UNIX; both modules check it in StartupModule and register
# nothing once past it. The header is removed after packaging and the plugin
# is rebuilt clean, so dev binaries never carry an expiry.
#
# IMPORTANT: a binary-only plugin loads ONLY on the exact same engine
# version it was built with (UnrealEditor.modules BuildId must match the
# recipient's UE install — same launcher version is fine, source builds are
# not). Recipient drops the unzipped GldfImporter/ into <Project>/Plugins/.

set -euo pipefail

DAYS="${1:-14}"
ROOT="$(cd "$(dirname "$0")" && pwd)"
PLUGIN="$ROOT/GldfImporter"
GLDF_RS="$(cd "$ROOT/../.." && pwd)"
PROJECT="$GLDF_RS/tmp/GldfArchTest/GldfArchTest.uproject"
UBT="/Users/Shared/Epic Games/UE_5.7/Engine/Build/BatchFiles/Mac/Build.sh"

EXPIRY_UNIX=$(date -v+"${DAYS}"d +%s)
EXPIRY_DATE=$(date -v+"${DAYS}"d +%Y-%m-%d)
OUT="$GLDF_RS/tmp/GldfImporter-Mac-eval-until-$EXPIRY_DATE.zip"

HEADERS=(
  "$PLUGIN/Source/GldfImporter/Private/GldfEvalExpiry.h"
  "$PLUGIN/Source/GldfSearch/Private/GldfEvalExpiry.h"
)

cleanup() {
  rm -f "${HEADERS[@]}"
}
trap cleanup EXIT

echo "=== eval build: expires $EXPIRY_DATE (unix $EXPIRY_UNIX) ==="
for H in "${HEADERS[@]}"; do
  printf '// GENERATED by package_eval_mac.sh — never commit.\n#define GLDF_EVAL_EXPIRY_UNIX %s\n' \
    "$EXPIRY_UNIX" > "$H"
done
# Force-recompile the gated sources: UBT's dep tracking doesn't notice a
# previously-missing __has_include header appearing, so an unchanged module
# cpp would otherwise keep its non-expiring object file.
touch "$PLUGIN/Source/GldfImporter/Private/GldfImporterModule.cpp" \
      "$PLUGIN/Source/GldfSearch/Private/GldfSearchModule.cpp"

"$UBT" UnrealEditor Mac Development -Project="$PROJECT"

echo "=== packaging $OUT ==="
rm -f "$OUT"
(cd "$ROOT" && zip -rq "$OUT" \
  GldfImporter/GldfImporter.uplugin \
  GldfImporter/Binaries/Mac \
  GldfImporter/Content \
  GldfImporter/README.md)

echo "=== rebuilding clean (no expiry) dev binaries ==="
cleanup
trap - EXIT
"$UBT" UnrealEditor Mac Development -Project="$PROJECT"

echo ""
echo "Done: $OUT"
unzip -l "$OUT" | tail -3
